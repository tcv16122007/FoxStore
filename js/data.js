function initData() {
    if (!localStorage.getItem("fox_products")) {
        localStorage.setItem("fox_products", JSON.stringify(DEFAULT_PRODUCTS));
    }
    if (!localStorage.getItem("fox_categories")) {
        localStorage.setItem("fox_categories", JSON.stringify(DEFAULT_CATEGORIES));
    }
    if (!localStorage.getItem("fox_orders")) {
        localStorage.setItem("fox_orders", JSON.stringify([]));
    }
    if (!localStorage.getItem("fox_messages")) {
        localStorage.setItem("fox_messages", JSON.stringify(DEFAULT_MESSAGES));
    }

    let users = JSON.parse(localStorage.getItem("fox_users")) || [];
    let changed = false;

    const OLD_ADMIN_EMAILS = ["owner@foxstore", "owner@foxstore.com"];
    users = users.map(u => {
        const c = { ...u };
        if (OLD_ADMIN_EMAILS.includes(c.email)) {
            c.email = "contact@foxstore.com";
            c.role = "admin";
            c.phone = "0987654321";
            c.username = "owner";
            c.password = "admin123";
            changed = true;
        }
        if (!c.username) { c.username = c.email.split("@")[0]; changed = true; }
        if (!c.shipperStatus) { c.shipperStatus = "none"; changed = true; }
        if (!c.role) { c.role = "user"; changed = true; }
        return c;
    });

    DEFAULT_USERS.forEach(def => {
        const existing = users.find(u =>
            u.email === def.email || u.username === def.username
        );
        if (!existing) {
            users.push({ ...def });
            changed = true;
        } else {
            if (existing.password !== def.password) { existing.password = def.password; changed = true; }
            if (existing.username !== def.username) { existing.username = def.username; changed = true; }
            if (existing.role !== def.role) { existing.role = def.role; changed = true; }
            if (existing.email !== def.email) { existing.email = def.email; changed = true; }
            if (existing.phone !== def.phone) { existing.phone = def.phone; changed = true; }
            if (existing.shipperStatus !== def.shipperStatus) { existing.shipperStatus = def.shipperStatus; changed = true; }
            if (existing.name !== def.name) { existing.name = def.name; changed = true; }
        }
    });

    if (changed) localStorage.setItem("fox_users", JSON.stringify(users));

    const products = getProducts();
    let pChanged = false;
    const migrated = products.map(p => {
        if (!p.images || !p.images.length) {
            pChanged = true;
            const base = p.image.replace(/\/\d+\/\d+$/, "");
            return { ...p, images: [`${base}/600/600`, `${base}/601/601`, `${base}/602/602`, `${base}/603/603`] };
        }
        return p;
    });
    if (pChanged) saveProducts(migrated);
}

function getProducts() { return JSON.parse(localStorage.getItem("fox_products")) || []; }
function saveProducts(list) { localStorage.setItem("fox_products", JSON.stringify(list)); }
function getCategories() { return JSON.parse(localStorage.getItem("fox_categories")) || []; }
function getProductById(id) { return getProducts().find(p => p.id === id); }
function getNextProductId() {
    const list = getProducts();
    return list.length ? Math.max(...list.map(p => p.id)) + 1 : 1;
}
function addProduct(data) {
    const list = getProducts();
    const n = { ...data, id: getNextProductId() };
    list.push(n);
    saveProducts(list);
    return n;
}
function updateProduct(id, data) {
    const list = getProducts();
    const i = list.findIndex(p => p.id === id);
    if (i === -1) return false;
    list[i] = { ...list[i], ...data, id };
    saveProducts(list);
    return true;
}
function deleteProduct(id) { saveProducts(getProducts().filter(p => p.id !== id)); }
function resetProducts() { saveProducts([...DEFAULT_PRODUCTS]); }

